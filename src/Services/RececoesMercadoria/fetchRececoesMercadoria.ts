interface FetchRececoesMercadoriaSAPDataI {
  estado: string;
  periodoData: string;
  pagina: number;
}

const dataTeste = "2024-02-14";
const estadoTeste = "boposReleased";
export const useFetchRececoesMercadoriaSAPData = (
  estado: FetchRececoesMercadoriaSAPDataI["estado"] = estadoTeste,
  periodoData: FetchRececoesMercadoriaSAPDataI["periodoData"] = dataTeste,
  pagina: FetchRececoesMercadoriaSAPDataI["pagina"] = 0
) => {
  return useQuery({
    queryKey: ["rececoesMercadoriaSAP",periodoData,pagina],
    queryFn: async () => {
      const { data } = await axios.get(
        `http://egiquim-sap:50001/b1s/v1/PurchaseDeliveryNotes?$filter=CreationDate ge '${periodoData}'&$skip=${pagina}`,
        { withCredentials: true }
      );
      return data as ApiResponse;
    },
    refetchInterval: 1000 * 60 * 5,
    refetchIntervalInBackground: true,
  });
};
